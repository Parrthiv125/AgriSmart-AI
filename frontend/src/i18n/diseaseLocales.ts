/**
 * Returns localized disease info for a given class ID or base DiseaseInfo object.
 * The classId remains unchanged in all languages.
 */
export function getLocalizedDisease(
  diseaseOrClassId: string | DiseaseInfo | null | undefined,
  language: SupportedLanguage = 'en'
): DiseaseInfo | null {
  if (!diseaseOrClassId) return null;

  const classId = typeof diseaseOrClassId === 'string' ? diseaseOrClassId : diseaseOrClassId.classId;
  const baseDisease = DISEASE_CATALOG[classId] || (typeof diseaseOrClassId === 'object' ? diseaseOrClassId : null);

  if (!baseDisease) return null;
  if (language === 'en') return baseDisease;

  const locale = DISEASE_LOCALIZATIONS[classId]?.[language];
  if (!locale) {
    // Fallback: translate crop name at least
    const localizedCrop = CROP_TRANSLATIONS[baseDisease.crop]?.[language] || baseDisease.crop;
    return {
      ...baseDisease,
      crop: localizedCrop
    };
  }

  return {
    ...baseDisease,
    displayName: locale.displayName || baseDisease.displayName,
    crop: locale.crop || CROP_TRANSLATIONS[baseDisease.crop]?.[language] || baseDisease.crop,
    description: locale.description || baseDisease.description,
    symptoms: locale.symptoms || baseDisease.symptoms,
    causes: locale.causes || baseDisease.causes,
    prevention: locale.prevention || baseDisease.prevention,
    treatment: locale.treatment || baseDisease.treatment,
    caution: locale.caution || baseDisease.caution
  };
}

/**
 * Returns all 28 localized disease objects for the current language.
 */
export function getAllLocalizedDiseases(language: SupportedLanguage = 'en'): DiseaseInfo[] {
  return ALL_DISEASE_CLASSES.map((disease) => getLocalizedDisease(disease, language)!);
}

